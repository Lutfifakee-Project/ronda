func TestUdevRunBareCommandNotTargeted(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	// Distribution helpers exist in this root; only their LOCATION and
	// traits decide findings, never their absence in a synthetic root.
	f.write("/usr/lib/udev/usb_modeswitch", "script")
	f.write("/lib/udev/scsi_id", "script")
	f.write("/lib/udev/hdparm", "script")
	f.write("/etc/udev/rules.d/68-helpers.rules", `ACTION=="add", SUBSYSTEM=="usb", RUN+="/usr/lib/udev/usb_modeswitch"
PROGRAM="/lib/udev/scsi_id --whitelisted", RUN+="/lib/udev/hdparm"
`)
	rep := f.scan()
	for _, fl := range rep.Findings {
		if fl.Rule == "udev-run-missing" {
			t.Fatalf("bare PATH-resolved helpers must not become missing-target findings: %s", fl.Evidence)
		}
	}
}

func TestUdevSymlinkEscapeNotFollowed(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	f.symlink("/etc/udev/escape", "../../../../outside-the-root")
	f.write("/etc/udev/rules.d/71-escape.rules", `ACTION=="add", RUN+="/etc/udev/escape"
`)
	rep := f.scan()
	// The escape must be neither followed nor classified as a normal
	// missing target; containment keeps the scan safe.
	for _, fl := range rep.Findings {
		if fl.Rule == "udev-run-suspicious" {
			t.Fatalf("escaped symlink reported as suspicious: %s", fl.Evidence)
		}
	}
}

