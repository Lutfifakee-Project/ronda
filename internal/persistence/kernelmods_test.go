// kmodTreeFixture writes a small kernel module tree containing the given
// module images.
func kmodTreeFixture(f *fixtureRoot, modules ...string) {
	for _, m := range modules {
		f.write("/lib/modules/6.1.0/kernel/drivers/"+m+"/"+m+".ko", elfBytes(62))
	}
}

func TestKmodStandardModulesNoFindings(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	kmodTreeFixture(f, "loop", "dm_mod")
	f.write("/etc/modules", "# /etc/modules: kernel modules to load at boot time\nloop\ndm_mod\n")
	rep := f.scan()
	for _, fl := range rep.Findings {
		if strings.HasPrefix(fl.Rule, "kmod-") && fl.Severity.Rank() >= finding.Medium.Rank() {
			t.Fatalf("standard module produced %s: %s", fl.Rule, fl.Evidence)
		}
	}
}

func TestKmodLegitimateCustomModule(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	kmodTreeFixture(f, "custom_driver")
	f.write("/etc/modules-load.d/custom.conf", "custom_driver\n")
	rep := f.scan()
	for _, fl := range rep.Findings {
		if fl.Rule == "kmod-missing-module" {
			t.Fatalf("present custom module reported missing: %s", fl.Evidence)
		}
	}
}

func TestKmodMissingModuleLowIndicator(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	kmodTreeFixture(f, "loop")
	f.write("/etc/modules", "loop\nghostmod\n")
	rep := f.scan()
	countRule(t, rep, "kmod-missing-module", 1)
	fl := findingsByRule(rep)["kmod-missing-module"][0]
	if fl.Severity != finding.Low {
		t.Errorf("missing module image is a weak indicator (LOW), got %s", fl.Severity)
	}
}

func TestKmodNoModuleTreeUnverified(t *testing.T) {
	f := newFixtureRoot(t)
	f.addPasswd()
	f.write("/etc/modules", "something\n")
	rep := f.scan()
	countRule(t, rep, "kmod-missing-module", 0)
	verified := false
	for _, u := range rep.Unverified {
		if strings.Contains(u, "no kernel module tree") {
			verified = true
		}
	}
	if !verified {
		t.Fatalf("absent module tree must be reported as unverified scope, got %v", rep.Unverified)
	}
}

